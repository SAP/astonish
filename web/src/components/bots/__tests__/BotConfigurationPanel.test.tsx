it('opts a saved elapsed deadline into health only through reviewed save, retaining other caps', async () => {
  const runtime_policy: policy.BotRuntimePolicy = { schema_version: 1, mode: 'progress_v1', evaluation_interval_seconds: 60, model_call_timeout_seconds: 120, tool_call_timeout_seconds: 40, max_active_seconds: 7200 }
  vi.mocked(policy.getBotConfigurationVersion).mockResolvedValue({ ...version, budget: { ...version.budget, runtime_policy } })
  render(<BotConfigurationPanel bot={bot} onChange={vi.fn()} />)
  expect(await screen.findByLabelText('Use generation health monitoring (explicit opt-in)')).not.toBeChecked()
  expect(screen.getByLabelText('Model operation timeout (seconds)')).toHaveValue(120)
  expect(screen.getByLabelText('Model operation timeout (seconds)')).toHaveAttribute('min', '1')
  fireEvent.click(screen.getByLabelText('Use generation health monitoring (explicit opt-in)'))
  expect(policy.configureBot).not.toHaveBeenCalled()
  expect(runtime_policy.model_call_timeout_seconds).toBe(120)
  expect(runtime_policy.generation_health).toBeUndefined()
  await review()
  const changes = screen.getByRole('region', { name: 'Review configuration changes' })
  expect(changes).toHaveTextContent('Model elapsed timeout 120s (saved deadline)')
  expect(changes).toHaveTextContent('No fixed generation duration')
  expect(changes).toHaveTextContent('Maximum 7200s active time')
  fireEvent.click(screen.getByLabelText('I reviewed this exact configuration and reason'))
  fireEvent.click(screen.getByLabelText('I explicitly authorize the rights, spending and delivery destinations shown above'))
  fireEvent.click(screen.getByRole('button', { name: 'Save reviewed configuration' }))
  await waitFor(() => expect(policy.configureBot).toHaveBeenCalledWith('bot', 'personal', expect.objectContaining({ expected_revision: 7, expected_version: 2, budget: { ...version.budget, runtime_policy: { ...runtime_policy, model_call_timeout_seconds: 0, generation_health: { idle_timeout_seconds: 120, check_interval_seconds: 10 } } } })))
})
