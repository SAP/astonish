it('uses one current-time formatter for both navigation sections', () => {
  const now = Date.now()
  expect(formatTimeAgo('')).toBe('')
  expect(formatTimeAgo('invalid')).toBe('')
  expect(formatTimeAgo(new Date(now).toISOString())).toBe('just now')
  expect(formatTimeAgo(new Date(now - 180000).toISOString())).toBe('3m ago')
  expect(formatTimeAgo(new Date(now - 7200000).toISOString())).toBe('2h ago')
  expect(formatTimeAgo(new Date(now - 172800000).toISOString())).toBe('2d ago')
  const older = new Date(now - 864000000)
  expect(formatTimeAgo(older.toISOString())).toBe(older.toLocaleDateString())
})
