import { beforeEach, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import BotConfigurationPanel from '../BotConfigurationPanel'
import * as policy from '@/api/botConfiguration'
import * as bots from '@/api/bots'
vi.mock('@/api/botConfiguration', async original => ({ ...await original<typeof policy>(), configureBot: vi.fn(), getBotConfigurationVersion: vi.fn() }))
vi.mock('@/api/bots', async original => ({ ...await original<typeof bots>(), getBot: vi.fn(), botLifecycle: vi.fn() }))
const bot = { id: 'bot', scope: 'personal', revision: 7, version: 2, status: 'draft' } as bots.Bot
const version = { bot_id: 'bot', version: 2, charter: 'Observe', persona: { language: '', timezone: 'UTC', soul: '', identity: '', user: '' }, triggers: [], autonomy: { level: 'supervised', allowed_tools: [], denied_tools: [], allowed_paths: [], allowed_hosts: [], can_contact_people: false, can_publish: false, max_spend_per_run_minor: 0, max_spend_per_month_minor: 0 }, budget: { max_runtime_seconds: 60 }, delivery: { notify: 'on_change', preferences: '', bindings: [] } } as policy.BotConfigurationVersion
beforeEach(() => { vi.clearAllMocks(); vi.mocked(policy.getBotConfigurationVersion).mockResolvedValue(version); vi.mocked(bots.getBot).mockResolvedValue(bot); vi.mocked(policy.configureBot).mockResolvedValue({ ...bot, version: 3, revision: 8 }) })
async function review() {
  fireEvent.change(await screen.findByLabelText('Review reason'), { target: { value: 'Reviewed operating limits' } })
  fireEvent.click(screen.getByRole('button', { name: 'Review configuration' }))
}
it('requires separate review and rights consent, sends pinned versions, and never activates', async () => {
  render(<BotConfigurationPanel bot={bot} onChange={vi.fn()} />)
  expect(await screen.findByLabelText('Autonomy level')).toBeInTheDocument()
  expect(screen.getByLabelText('Autonomy level').querySelectorAll('option')).toHaveLength(4)
  fireEvent.click(screen.getByLabelText('May contact people'))
  await review()
  expect(policy.configureBot).not.toHaveBeenCalled()
  expect(screen.getByRole('button', { name: 'Save reviewed configuration' })).toBeDisabled()
  fireEvent.click(screen.getByLabelText('I reviewed this exact configuration and reason'))
  expect(screen.getByRole('button', { name: 'Save reviewed configuration' })).toBeDisabled()
  fireEvent.click(screen.getByLabelText('I explicitly authorize the rights, spending and delivery destinations shown above'))
  fireEvent.click(screen.getByRole('button', { name: 'Save reviewed configuration' }))
  await waitFor(() => expect(policy.configureBot).toHaveBeenCalledWith('bot', 'personal', expect.objectContaining({ expected_revision: 7, expected_version: 2, reviewed: true, reason: 'Reviewed operating limits', autonomy: expect.objectContaining({ can_contact_people: true }) })))
  expect(bots.botLifecycle).not.toHaveBeenCalled()
})
it('keeps edits and old CAS on conflict and requires explicit refresh and renewed review', async () => {
  vi.mocked(policy.configureBot).mockRejectedValue(new bots.BotAPIError(409, 'revision conflict'))
  const view = render(<BotConfigurationPanel bot={bot} onChange={vi.fn()} />)
  fireEvent.change(await screen.findByLabelText('Allowed hosts (one per line)'), { target: { value: 'example.org' } })
  await review()
  fireEvent.click(screen.getByLabelText('I reviewed this exact configuration and reason'))
  fireEvent.click(screen.getByLabelText('I explicitly authorize the rights, spending and delivery destinations shown above'))
  fireEvent.click(screen.getByRole('button', { name: 'Save reviewed configuration' }))
  await screen.findByText(/revision conflict/)
  view.rerender(<BotConfigurationPanel bot={{ ...bot, revision: 8, version: 3 }} onChange={vi.fn()} />)
  expect(screen.getByLabelText('Allowed hosts (one per line)')).toHaveValue('example.org')
  expect(policy.configureBot).toHaveBeenCalledTimes(1)
  vi.mocked(bots.getBot).mockResolvedValue({ ...bot, revision: 8, version: 3 })
  vi.mocked(policy.getBotConfigurationVersion).mockResolvedValue({ ...version, version: 3 })
  fireEvent.click(screen.getByRole('button', { name: 'Load latest baseline, keep edits' }))
  await screen.findByText(/Baseline: revision 8 · version 3/)
  expect(screen.getByLabelText('Allowed hosts (one per line)')).toHaveValue('example.org')
  expect(screen.queryByRole('button', { name: 'Save reviewed configuration' })).not.toBeInTheDocument()
})
it.each(['active', 'deleted'] as const)('does not allow configuration of %s Bots', async status => {
  render(<BotConfigurationPanel bot={{ ...bot, status }} onChange={vi.fn()} />)
  expect(await screen.findByLabelText('Autonomy level')).toBeDisabled()
  expect(screen.getByRole('button', { name: 'Review configuration' })).toBeDisabled()
  expect(policy.configureBot).not.toHaveBeenCalled()
})
it('invalidates consent on edits and preserves explicit zero budgets and delivery thread IDs', async () => {
  render(<BotConfigurationPanel bot={bot} onChange={vi.fn()} />)
  fireEvent.change(await screen.findByLabelText('Maximum tokens'), { target: { value: '0' } })
  fireEvent.click(screen.getByRole('button', { name: 'Add delivery destination' }))
  for (const [label, value] of Object.entries({ 'Linked identity ID': 'linked', Channel: 'telegram', 'Chat ID': '123', 'Thread ID (optional)': '456' })) fireEvent.change(screen.getByLabelText(label), { target: { value } })
  await review()
  fireEvent.click(screen.getByLabelText('I reviewed this exact configuration and reason'))
  fireEvent.click(screen.getByLabelText('I explicitly authorize the rights, spending and delivery destinations shown above'))
  fireEvent.change(screen.getByLabelText('Delivery preferences'), { target: { value: 'Concise' } })
  expect(screen.queryByRole('button', { name: 'Save reviewed configuration' })).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Review configuration' }))
  expect(screen.getByLabelText('I reviewed this exact configuration and reason')).not.toBeChecked()
  expect(screen.getByLabelText('I explicitly authorize the rights, spending and delivery destinations shown above')).not.toBeChecked()
  fireEvent.click(screen.getByLabelText('I reviewed this exact configuration and reason'))
  fireEvent.click(screen.getByLabelText('I explicitly authorize the rights, spending and delivery destinations shown above'))
  fireEvent.click(screen.getByRole('button', { name: 'Save reviewed configuration' }))
  await waitFor(() => expect(policy.configureBot).toHaveBeenCalledWith('bot', 'personal', expect.objectContaining({ budget: { max_runtime_seconds: 60, max_tokens: 0 }, delivery: { notify: 'on_change', preferences: 'Concise', bindings: [{ id: 'linked', channel: 'telegram', chat_id: '123', thread_id: '456' }] } })))
})
it('preserves fields and surfaces unsupported save errors without assuming capability', async () => {
  vi.mocked(policy.configureBot).mockRejectedValue(new bots.BotAPIError(501, 'Destination proof unsupported'))
  render(<BotConfigurationPanel bot={bot} onChange={vi.fn()} />)
  fireEvent.change(await screen.findByLabelText('Delivery preferences'), { target: { value: 'Keep this' } })
  await review()
  fireEvent.click(screen.getByLabelText('I reviewed this exact configuration and reason'))
  fireEvent.click(screen.getByLabelText('I explicitly authorize the rights, spending and delivery destinations shown above'))
  fireEvent.click(screen.getByRole('button', { name: 'Save reviewed configuration' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('Destination proof unsupported')
  expect(screen.getByLabelText('Delivery preferences')).toHaveValue('Keep this')
  expect(screen.getByRole('button', { name: 'Save reviewed configuration' })).toBeDisabled()
})
it('shows unsupported loading errors and disables read-only configuration', async () => {
  vi.mocked(policy.getBotConfigurationVersion).mockRejectedValue(new bots.BotAPIError(501, 'Not supported here'))
  render(<BotConfigurationPanel bot={bot} onChange={vi.fn()} readOnly />)
  expect(await screen.findByRole('alert')).toHaveTextContent('Not supported here')
  expect(policy.configureBot).not.toHaveBeenCalled()
})
