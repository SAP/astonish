it('rejects invalid health combinations and invalidates consent on health edits', async () => {
  vi.mocked(policy.getBotConfigurationVersion).mockResolvedValue({ ...version, budget: { ...version.budget, runtime_policy: policy.newBotProgressRuntimePolicy() } })
  render(<BotConfigurationPanel bot={bot} onChange={vi.fn()} />)
  await review()
  fireEvent.click(screen.getByLabelText('I reviewed this exact configuration and reason'))
  fireEvent.change(screen.getByLabelText('Generation health check interval (seconds)'), { target: { value: '121' } })
  expect(screen.queryByRole('button', { name: 'Save reviewed configuration' })).not.toBeInTheDocument()
  fireEvent.submit(screen.getByLabelText('Review reason').closest('form')!)
  expect(await screen.findByRole('alert')).toHaveTextContent('Health checks must not exceed')
  fireEvent.change(screen.getByLabelText('Generation health check interval (seconds)'), { target: { value: '10' } })
  fireEvent.change(screen.getByLabelText('Model operation timeout (seconds)'), { target: { value: '120' } })
  fireEvent.submit(screen.getByLabelText('Review reason').closest('form')!)
  expect(screen.queryByRole('button', { name: 'Save reviewed configuration' })).not.toBeInTheDocument()
  expect(policy.configureBot).not.toHaveBeenCalled()
})
