it.each([false, true])('shows accessible empty, loading and retry states (collapsed=%s)', async collapsed => {
  vi.mocked(bots.listBots).mockResolvedValue({ bots: [] })
  const { unmount } = render(<BotSidebar collapsed={collapsed} />)
  expect(screen.getByRole('button', { name: collapsed ? 'Show Bots' : 'New Bot' })).toBeInTheDocument()
  expect(screen.getByRole('status')).toHaveTextContent('Loading Bots')
  expect(await screen.findByText('No Bots yet. Create a reviewed draft.')).toBeInTheDocument()
  unmount()
  vi.mocked(bots.listBots).mockRejectedValue(new Error('Offline'))
  render(<BotSidebar collapsed={collapsed} />)
  expect(await screen.findByRole('button', { name: 'Retry Bots' })).toBeInTheDocument()
  expect(screen.getByRole('alert')).toHaveTextContent('Offline')
  expect(screen.getByRole('button', { name: collapsed ? 'Show Bots' : 'New Bot' })).toBeInTheDocument()
  vi.mocked(bots.listBots).mockResolvedValue({ bots: [bot] })
  fireEvent.click(screen.getByRole('button', { name: 'Retry Bots' }))
  expect(await screen.findByRole('link', { name: /Watcher/ })).toBeInTheDocument()
})
it('ignores an old scope response after switching filters', async () => {
  let resolvePrivate!: (value: { bots: bots.Bot[] }) => void
  const privateRequest = new Promise<{ bots: bots.Bot[] }>(resolve => { resolvePrivate = resolve })
  vi.mocked(bots.listBots).mockImplementation(scope => scope === 'personal' ? privateRequest : Promise.resolve({ bots: [{ ...bot, scope: 'team', name: 'Team watcher' }] }))
  render(<BotSidebar activeId={bot.id} activeScope="personal" />)
  await waitFor(() => expect(bots.listBots).toHaveBeenCalled())
  fireEvent.click(screen.getByRole('button', { name: 'Team' }))
  expect(await screen.findByRole('link', { name: 'Team watcher' })).toHaveAttribute('href', '#/chat/bots/team/ordinary-uuid')
  await act(async () => { resolvePrivate({ bots: [bot] }); await privateRequest })
  expect(screen.queryByRole('link', { name: 'Watcher' })).not.toBeInTheDocument()
  expect(screen.getByRole('link')).not.toHaveAttribute('aria-current')
})
