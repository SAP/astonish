import { beforeEach, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { BotMemoryCharterPanel } from '../BotPanels'
import * as api from '@/api/botMemory'
import { BotAPIError, type Bot } from '@/api/bots'
vi.mock('@/api/botMemory', () => ({ getBotDocuments: vi.fn(), getBotMemoryHealth: vi.fn(), saveBotDocument: vi.fn(), submitBotCorrection: vi.fn(), reconcileBotCorrection: vi.fn() }))
const bot = { id: 'bot', scope: 'personal', revision: 2, version: 1 } as Bot
const projection = { bot_id: 'bot', revision: 2, version: 1, documents: [{ name: 'SOUL.md', content: 'Original' }, { name: 'MEMORY.md', content: 'Projected evidence', read_only: true, source_version: 'fingerprint' }] }
beforeEach(() => {
  vi.clearAllMocks()
  vi.mocked(api.getBotDocuments).mockResolvedValue(projection)
  vi.mocked(api.getBotMemoryHealth).mockResolvedValue({ bot_id: 'bot', scope: 'personal', review_only: true, apply_supported: true, snapshot: { records: [{ id: 'memory', snippet: 'Thursday', path: 'source', session_id: 'session', created_by: 'owner' }], fingerprints: {}, fingerprint: 'hash', truncated: false, evaluated_at: 'today' }, health: { recommendation_count: 0, recommendations: [], evaluated_at: 'today' } })
})
it('requires review and reason and preserves local edits across conflict comparison', async () => {
  vi.mocked(api.saveBotDocument).mockRejectedValue(new BotAPIError(409, 'revision conflict'))
  render(<BotMemoryCharterPanel bot={bot} readOnly={false} />)
  fireEvent.change(await screen.findByLabelText('Content SOUL.md'), { target: { value: 'Local' } })
  fireEvent.change(screen.getByLabelText('Reason SOUL.md'), { target: { value: 'Reviewed correction' } })
  fireEvent.click(screen.getByRole('button', { name: 'Review SOUL.md' }))
  expect(api.saveBotDocument).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Confirm save SOUL.md' }))
  expect(await screen.findByText(/revision conflict/)).toBeInTheDocument()
  vi.mocked(api.getBotDocuments).mockResolvedValue({ ...projection, revision: 3, documents: [{ name: 'SOUL.md', content: 'Remote' }] })
  fireEvent.click(screen.getByRole('button', { name: 'Reload and compare SOUL.md' }))
  expect(await screen.findByText('Remote')).toBeInTheDocument()
  expect(screen.getByLabelText('Content SOUL.md')).toHaveValue('Local')
  expect(screen.getByRole('button', { name: 'Review SOUL.md' })).toBeDisabled()
  fireEvent.click(screen.getByRole('button', { name: 'Use latest revision; keep my edits SOUL.md' }))
  fireEvent.click(screen.getByRole('button', { name: 'Review SOUL.md' }))
  fireEvent.click(screen.getByRole('button', { name: 'Confirm save SOUL.md' }))
  await waitFor(() => expect(api.saveBotDocument).toHaveBeenLastCalledWith(bot, 'SOUL.md', { expected_revision: 3, content: 'Local', reason: 'Reviewed correction', confirmed: true }))
})
it('renders provenance and read-only documents without deriving authority from prose', async () => {
  render(<BotMemoryCharterPanel bot={bot} readOnly />)
  expect(await screen.findByLabelText('Content SOUL.md')).toBeDisabled()
  expect(await screen.findByText(/Session: session/)).toBeInTheDocument()
  expect(screen.getByText(/Creator: owner/)).toBeInTheDocument()
  expect(screen.queryByRole('button', { name: 'Review MEMORY.md' })).not.toBeInTheDocument()
  expect(screen.getByText('No health recommendations.')).toBeInTheDocument()
})
it('keeps health failure independent and supports retry', async () => {
  vi.mocked(api.getBotMemoryHealth).mockRejectedValueOnce(new Error('Health offline'))
  render(<BotMemoryCharterPanel bot={bot} readOnly={false} />)
  expect(await screen.findByText('Health offline')).toBeInTheDocument()
  expect(screen.getByLabelText('Content SOUL.md')).toHaveValue('Original')
  fireEvent.click(screen.getByRole('button', { name: 'Retry Memory Health' }))
  expect(await screen.findByText('No health recommendations.')).toBeInTheDocument()
})
it('keeps drafts through parent revision refresh and invalidates review after editing', async () => {
  const view = render(<BotMemoryCharterPanel bot={bot} readOnly={false} />)
  fireEvent.change(await screen.findByLabelText('Content SOUL.md'), { target: { value: 'Local draft' } })
  fireEvent.change(screen.getByLabelText('Reason SOUL.md'), { target: { value: 'Verified' } })
  fireEvent.click(screen.getByRole('button', { name: 'Review SOUL.md' }))
  view.rerender(<BotMemoryCharterPanel bot={{ ...bot, revision: 8 }} readOnly={false} />)
  expect(screen.getByLabelText('Content SOUL.md')).toHaveValue('Local draft')
  fireEvent.change(screen.getByLabelText('Content SOUL.md'), { target: { value: 'Changed after review' } })
  expect(screen.queryByRole('button', { name: 'Confirm save SOUL.md' })).not.toBeInTheDocument()
  expect(api.saveBotDocument).not.toHaveBeenCalled()
})
it('shows independent empty documents and memory states', async () => {
  vi.mocked(api.getBotDocuments).mockResolvedValue({ ...projection, documents: [] })
  const health = await api.getBotMemoryHealth(bot)
  vi.mocked(api.getBotMemoryHealth).mockResolvedValue({ ...health, snapshot: { ...health.snapshot, records: [] } })
  render(<BotMemoryCharterPanel bot={bot} readOnly={false} />)
  expect(await screen.findByText('No documents available.')).toBeInTheDocument()
  expect(await screen.findByText('No memory records yet.')).toBeInTheDocument()
})
it('records reviewed correction intent before a separate reconcile action', async () => {
  vi.mocked(api.submitBotCorrection).mockResolvedValue({ id: 'correction', intent: 'reconcile' })
  vi.mocked(api.reconcileBotCorrection).mockResolvedValue({ id: 'correction', memory_applied: true })
  render(<BotMemoryCharterPanel bot={bot} readOnly={false} />)
  fireEvent.click(await screen.findByRole('button', { name: 'Correct memory' }))
  fireEvent.change(screen.getByLabelText('Replacement'), { target: { value: 'Friday' } })
  fireEvent.change(screen.getByLabelText('Correction evidence'), { target: { value: 'Calendar verified' } })
  fireEvent.change(screen.getByLabelText('Evidence source'), { target: { value: 'calendar' } })
  fireEvent.click(screen.getByRole('button', { name: 'Review correction' }))
  expect(api.submitBotCorrection).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Confirm correction' }))
  expect(await screen.findByText(/Recorded for reconciliation/)).toBeInTheDocument()
  expect(api.reconcileBotCorrection).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Apply saved correction to memory' }))
  expect(await screen.findByText('Memory correction applied.')).toBeInTheDocument()
})
